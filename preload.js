'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');

const EVENTS = new Set(['tasks:changed', 'handoff:changed', 'item:upsert', 'item:remove', 'note:changed', 'activity', 'agent:touch', 'agent:active', 'paused', 'trading:changed', 'keys:changed', 'library:changed', 'focus:item', 'file:changed', 'mcp:status', 'item:action', 'cursor', 'chat:event', 'agents:changed', 'engine:status', 'team:changed', 'adblock:count', 'brave:frame', 'brave:state', 'software:status', 'tokens', 'connectors:status', 'peek:record']);

const invoke = (ch, ...a) => ipcRenderer.invoke(ch, ...a);

contextBridge.exposeInMainWorld('ac', {
  on(channel, cb) {
    if (!EVENTS.has(channel)) throw new Error(`Unknown event ${channel}`);
    const fn = (_e, ...args) => cb(...args);
    ipcRenderer.on(channel, fn);
    return () => ipcRenderer.removeListener(channel, fn);
  },
  feature: (name, args) => invoke('features:command', name, args),
  init: () => invoke('init'),
  addItem: p => invoke('item:add', p),
  updateItem: (id, patch) => invoke('item:update', id, patch),
  removeItem: id => invoke('item:remove', id),
  setViewport: v => invoke('viewport:set', v),
  browserAttached: (itemId, wcId) => ipcRenderer.send('browser:attached', itemId, wcId),
  browserDetached: itemId => ipcRenderer.send('browser:detached', itemId),
  noteRead: id => invoke('note:read', id),
  noteWrite: (id, content) => invoke('note:write', id, content),
  pathForFile: file => webUtils.getPathForFile(file),
  importFiles: paths => invoke('files:import', paths),
  importDialog: kind => invoke('files:importDialog', kind),
  exportFile: rel => invoke('file:export', rel),
  readText: rel => invoke('file:readText', rel),
  writeText: (rel, content) => invoke('file:writeText', rel, content),
  listDir: rel => invoke('dir:list', rel),
  library: q => invoke('library', q),
  keysList: () => invoke('keys:list'),
  keysSave: e => invoke('keys:save', e),
  keysDelete: id => invoke('keys:delete', id),
  keysTest: id => invoke('keys:test', id),
  exchanges: () => invoke('exchanges:list'),
  tradingState: () => invoke('trading:state'),
  setMandate: m => invoke('trading:setMandate', m),
  placeOrder: o => invoke('trading:order', o),
  cancelOrder: o => invoke('trading:cancel', o),
  balance: id => invoke('trading:balance', id),
  openOrders: id => invoke('trading:openOrders', id),
  ticker: (id, s) => invoke('trading:ticker', id, s),
  paperReset: amount => invoke('trading:paperReset', amount),
  acceptDisclaimer: () => invoke('settings:acceptDisclaimer'),
  mcpStatus: () => invoke('mcp:status'),
  mcpRegenerate: () => invoke('mcp:regenerateToken'),
  mcpConfigure: c => invoke('mcp:configure', c),
  setPaused: v => invoke('agent:setPaused', v),
  activity: () => invoke('activity:list'),
  openDataFolder: () => invoke('shell:openDataFolder'),
  openModelsFolder: () => invoke('shell:openModelsFolder'),
  copy: t => invoke('clipboard:write', t),
  setUi: patch => invoke('settings:setUi', patch),
  stats: () => invoke('stats'),
  duplicateFile: rel => invoke('file:duplicate', rel),
  triggerPaste: () => invoke('clipboard:paste'),
  savePasted: (name, bytes) => invoke('file:savePasted', name, bytes),
  clearBrowserData: profile => invoke('browser:clearData', profile),
  resetWorkspace: word => invoke('workspace:reset', word),
  agentsList: () => invoke('agents:list'),
  agentsUpdate: (name, patch) => invoke('agents:update', name, patch),
  agentsForget: name => invoke('agents:forget', name),
  mcpTools: () => invoke('mcp:tools'),
  // Agent calls take the agent id first; null means the first agent.
  llmState: id => invoke('llm:state', id),
  llmDetect: () => invoke('llm:detect'),
  llmModels: (runner, baseUrl, apiKey) => invoke('llm:models', runner, baseUrl, apiKey),
  llmModelInfo: (runner, baseUrl, model) => invoke('llm:modelInfo', runner, baseUrl, model),
  llmSetConfig: (id, patch) => invoke('llm:setConfig', id, patch),
  llmSend: (id, text) => invoke('llm:send', id, text),
  llmStop: id => invoke('llm:stop', id),
  llmReset: id => invoke('llm:reset', id),
  teamList: () => invoke('team:list'),
  teamAdd: opts => invoke('team:add', opts),
  teamDuplicate: id => invoke('team:duplicate', id),
  teamUpdate: (id, patch) => invoke('team:update', id, patch),
  teamRemove: id => invoke('team:remove', id),
  teamSendMany: tasks => invoke('team:sendMany', tasks),
  engineStatus: () => invoke('engine:status'),
  engineInstall: variant => invoke('engine:install', variant),
  engineStop: () => invoke('engine:stop'),
  adblockStatus: () => invoke('adblock:status'),
  adblockConfigure: patch => invoke('adblock:configure', patch),
  adblockSetBrowser: (profile, on) => invoke('adblock:setBrowser', profile, on),
  adblockAllowSite: (host, allow) => invoke('adblock:allowSite', host, allow),
  // Brave windows: the picture comes in as brave:frame, the user's input goes out here.
  braveHello: id => invoke('brave:hello', id),
  braveInput: (id, ev) => ipcRenderer.send('brave:input', id, ev),
  braveView: (id, v) => invoke('brave:view', id, v),
  braveNav: (id, what) => invoke('brave:nav', id, what),
  braveDialog: (id, accept, text) => invoke('brave:dialog', id, accept, text),
  braveReopen: id => invoke('brave:reopen', id),
  // Peek: a picture or clip of what an agent is doing.
  peekTarget: name => invoke('peek:target', name),
  peekFrame: id => invoke('peek:frame', id),
  peekRecorded: (id, bytes, mime, error) => invoke('peek:recorded', id, bytes, mime, error),
  braveSignIn: (id, done) => invoke('brave:signin', id, done),
  braveTab: (id, action, index) => invoke('brave:tab', id, action, index),
  softwareStatus: () => invoke('software:status'),
  softwareInstall: id => invoke('software:install', id),
  softwareRemove: id => invoke('software:remove', id),
  setBrowserEngine: choice => invoke('browser:setEngine', choice),
  openBrowserIn: (id, choice) => invoke('browser:openIn', id, choice),
  ramStats: () => invoke('stats:ram'),
  tokens: () => invoke('tokens:get'),
  tokensReset: () => invoke('tokens:reset'),
  organize: () => invoke('canvas:organize'),
  teamBroadcast: (ids, text) => invoke('team:broadcast', ids, text),
  teamWrapUp: ids => invoke('team:wrapUp', ids),
  agentPrefs: () => invoke('agents:prefs'),
  setAgentPrefs: patch => invoke('agents:setPrefs', patch),
  connectorsStatus: () => invoke('connectors:status'),
  connectorsConfigure: (id, patch) => invoke('connectors:configure', id, patch),
  connectorsPair: id => invoke('connectors:pair', id),
  connectorsUnlink: (id, chatId) => invoke('connectors:unlink', id, chatId),
  connectorsLinkAgent: (id, chatId, agentId) => invoke('connectors:linkAgent', id, chatId, agentId),
  connectorsTest: () => invoke('connectors:test'),
});
